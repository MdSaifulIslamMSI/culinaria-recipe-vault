/**
 * Rebuild the Recipe Catalog knowledge base
 * Fetches across alphabet A-Z from TheMealDB and writes src/data/recipeCatalog.js
 * (a single ES-module source shared by both the Vite client and the Node server)
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const alphabet = 'abcdefghijklmnopqrstuvwxyz'.split('');
const DATA_DIR = path.resolve(__dirname, '../src/data');

if (!fs.existsSync(DATA_DIR)) {
  fs.mkdirSync(DATA_DIR, { recursive: true });
}

async function fetchCatalog() {
  console.log('📦 Fetching recipes for the offline catalog...');
  const mealMap = new Map();

  for (const letter of alphabet) {
    try {
      const res = await fetch(`https://www.themealdb.com/api/json/v1/1/search.php?f=${letter}`);
      if (res.ok) {
        const data = await res.json();
        if (data && data.meals) {
          data.meals.forEach(m => {
            if (m && m.idMeal && !mealMap.has(m.idMeal)) {
              mealMap.set(m.idMeal, m);
            }
          });
        }
      }
    } catch (e) {
      console.warn(`Could not fetch letter ${letter}:`, e.message);
    }
  }

  console.log(`✨ Total unique recipes gathered: ${mealMap.size}`);

  const allMeals = Array.from(mealMap.values());
  const outputPath = path.join(DATA_DIR, 'recipeCatalog.js');
  const header = `/**\n * Culinaria Recipe Catalog (${allMeals.length} recipes)\n * Generated by scripts/fetch-recipe-catalog.js — do not edit by hand.\n */\nexport default `;
  fs.writeFileSync(outputPath, header + JSON.stringify(allMeals) + ';\n');
  console.log(`💾 Saved ${allMeals.length} recipes to ${outputPath}`);
}

fetchCatalog().catch(console.error);
